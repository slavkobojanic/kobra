#[test]
fn generator_exhausted_input_yields_a_valid_program() {
    // With no bytes every choice is the first option: still a valid program.
    let program = kgen::generate(&mut Unstructured::new(&[]));
    assert!(program.valid);
    assert_clean(&program);
}

#[test]
fn generator_covers_both_modes_and_many_shapes() {
    // A cheap sanity check that the generator is not degenerate: across
    // deterministic pseudo-random inputs it produces both modes and a
    // variety of declarations.
    let mut state = 0x9e37_79b9_7f4a_7c15u64;
    let mut seen_valid = 0;
    let mut seen_noisy = 0;
    let mut keywords = std::collections::BTreeSet::new();
    for _ in 0..400 {
        let bytes: Vec<u8> = (0..2048)
            .map(|_| {
                state ^= state << 13;
                state ^= state >> 7;
                state ^= state << 17;
                state.to_le_bytes()[0]
            })
            .collect();
        let program = kgen::generate(&mut Unstructured::new(&bytes));
        if program.valid {
            seen_valid += 1;
        } else {
            seen_noisy += 1;
        }
        for word in [
            "component",
            "page",
            "struct",
            "enum",
            "style",
            "view",
            "match",
            "for",
            "test",
            "rpc",
            "theme",
            "extend",
        ] {
            if program.source.contains(word) {
                keywords.insert(word);
            }
        }
        assert_clean(&program);
    }
    assert!(
        seen_valid > 100 && seen_noisy > 50,
        "{seen_valid} {seen_noisy}"
    );
    assert_eq!(
        keywords.len(),
        12,
        "generator never produced some of: {keywords:?}"
    );
}

/// Former violations of the "no diagnostic is reported twice" property,
/// found by `duplicate_diagnostics_are_never_reported` below. Each is also a
/// corpus case under `tests/corpus/parser/regressions/duplicate-diagnostic-*`.
const FORMER_DUPLICATES: &[&str] = &[
    // K0100 at `<` twice: "expected a name, found `<`" and "expected a
    // generic parameter name".
    "enum<",
    // K0100 "expected `{`, found end of file" twice at the end of the file:
    // once for the unfinished `match` and once for the enclosing `if`.
    "layout y{loading{if(match(",
];

#[test]
fn former_duplicate_diagnostics_stay_fixed() {
    for text in FORMER_DUPLICATES {
        let parse = check_all(text);
        oracle::check_no_duplicates(&parse);
    }
}

proptest! {
    #![proptest_config(ProptestConfig { cases: 384, ..ProptestConfig::default() })]

    /// No diagnostic (same code, same span) is reported twice. (`check_all`
    /// checks this too; this property names it on its own.)
    #[test]
    fn duplicate_diagnostics_are_never_reported(program in generated()) {
        let parse = check_all(&program.source);
        oracle::check_no_duplicates(&parse);
    }
}
