/// Generates text by concatenating up to 95 K-like fragments.
fn k_shaped() -> impl Strategy<Value = String> {
    prop::collection::vec(prop::sample::select(FRAGMENTS), 0..96).prop_map(|parts| parts.concat())
}

/// Generates up to 511 random bytes decoded lossily as UTF-8, so invalid
/// sequences become U+FFFD.
fn lossy_bytes() -> impl Strategy<Value = String> {
    prop::collection::vec(any::<u8>(), 0..512)
        .prop_map(|bytes| String::from_utf8_lossy(&bytes).into_owned())
}

/// Generates a program from proptest bytes with the structure-aware
/// generator.
fn generated() -> impl Strategy<Value = kgen::Generated> {
    prop::collection::vec(any::<u8>(), 0..4096)
        .prop_map(|bytes| kgen::generate(&mut Unstructured::new(&bytes)))
}

/// Asserts that a valid-mode program parses without diagnostics.
fn assert_clean(program: &kgen::Generated) {
    let parse = check_all(&program.source);
    if program.valid {
        assert!(
            parse.diagnostics().is_empty(),
            "valid program has diagnostics: {:#?}\n--- source ---\n{}",
            parse.diagnostics(),
            program.source
        );
    }
}

proptest! {
    #![proptest_config(ProptestConfig { cases: 384, ..ProptestConfig::default() })]

    #[test]
    fn arbitrary_text_keeps_every_invariant(text in any::<String>()) {
        check_all(&text);
    }

    #[test]
    fn lossy_bytes_keep_every_invariant(text in lossy_bytes()) {
        check_all(&text);
    }

    #[test]
    fn k_shaped_text_keeps_every_invariant(text in k_shaped()) {
        check_all(&text);
    }

    #[test]
    fn generated_programs_keep_every_invariant(program in generated()) {
        assert_clean(&program);
    }

    #[test]
    fn valid_programs_survive_any_single_cut(program in generated(), cut in any::<prop::sample::Index>()) {
        // Truncating a program anywhere (on a char boundary) models typing:
        // every prefix must still keep every invariant.
        let source = &program.source;
        let mut at = cut.index(source.len() + 1);
        while !source.is_char_boundary(at) {
            at -= 1;
        }
        check_all(&source[..at]);
    }

    #[test]
    fn splicing_two_texts_keeps_every_invariant(a in k_shaped(), b in generated()) {
        // Insert broken syntax into the middle of a well-formed program.
        let source = &b.source;
        let mut at = source.len() / 2;
        while !source.is_char_boundary(at) {
            at -= 1;
        }
        let spliced = format!("{}{a}{}", &source[..at], &source[at..]);
        check_all(&spliced);
    }

    #[test]
    fn parsing_is_independent_of_the_file_id(text in k_shaped(), raw in 0u32..1000) {
        // The file id only tags spans; it must not change anything else.
        let file = k_diagnostics::FileId::new(raw);
        let a = parse(FILE, &text);
        let b = parse(file, &text);
        prop_assert_eq!(a.green(), b.green());
        prop_assert_eq!(a.diagnostics().len(), b.diagnostics().len());
        for (x, y) in a.diagnostics().iter().zip(b.diagnostics()) {
            prop_assert_eq!(y.span.file, file);
            prop_assert_eq!(x.code, y.code);
            prop_assert_eq!(x.span.range, y.span.range);
            prop_assert_eq!(&x.message, &y.message);
        }
        let lexed = lex(file, &text);
        prop_assert!(lexed.diagnostics().iter().all(|d| d.span.file == file));
    }
}

