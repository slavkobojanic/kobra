//! Property tests for the syntax layer, run on stable with proptest.
//!
//! Every property is checked by the shared oracle in `support/oracle.rs`,
//! the same code the nightly fuzz targets in `fuzz/` run, over three input
//! families:
//!
//! * **arbitrary text**: any Unicode string, and any byte string decoded
//!   lossily (so invalid UTF-8 becomes U+FFFD, a non-ASCII error character);
//! * **K-shaped text**: fragments of real and broken K syntax glued together,
//!   which reaches the lexer's string, interpolation and style modes;
//! * **generated programs**: the structure-aware generator in
//!   `support/kgen.rs`, fed with proptest-generated bytes. Programs
//!   generated in valid mode must parse without any diagnostic.
//!
//! The properties:
//!
//! 1. lexing and parsing never panic;
//! 2. the tree is lossless: its text equals the input exactly;
//! 3. every diagnostic span (primary, labels, fix edits) lies within the file
//!    and on char boundaries, codes are registered and diagnostics are sorted;
//! 4. the tree's tokens are the lexer's tokens, and re-lexing their texts
//!    reproduces the token stream;
//! 5. lexing and parsing are deterministic;
//! 6. the number of diagnostics is bounded by `oracle::max_diagnostics` of
//!    the number of non-trivia tokens, and no diagnostic is reported twice;
//! 7. the `.tokens` and `.ast` dumps read back to what was written.
//!
//! `PROPTEST_CASES=N` raises the number of cases per property. Failures are
//! shrunk and persisted in `properties.proptest-regressions`; turn each into
//! a corpus regression case (docs/compiler/testing.md, "Regression tests").

