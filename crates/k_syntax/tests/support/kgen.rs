//! A structure-aware generator of K source text, driven by the [`arbitrary`]
//! crate.
//!
//! [`generate`] reads choices from an [`Unstructured`] byte source and
//! writes a K program by walking the grammar of `docs/compiler/grammar.md`:
//! imports, every kind of declaration, members, statements, expressions,
//! patterns, types, views, style blocks and tests, with trivia (comments,
//! blank lines, CRLF) in between. Fuzzers mutate the bytes, so they explore
//! the grammar instead of the space of random characters, which mostly
//! fails in the lexer.
//!
//! A program is generated in one of two modes, chosen by the first byte:
//!
//! * **Valid** ([`Generated::valid`] is `true`): only well-formed syntax is
//!   written, so the parser must report *no* diagnostics. This turns the
//!   generator into an oracle for wrong errors, not only for crashes.
//! * **Noisy**: the same walk, but each token may be dropped, duplicated or
//!   preceded by a fragment of broken syntax. This reaches error recovery
//!   from realistic surroundings.
//!
//! The generator never fails: when the byte source runs out, every choice
//! falls back to its first (smallest) option, and a node budget and a depth
//! limit bound the output.
//!
//! This file is shared by `crates/k_syntax/tests/properties.rs` (stable,
//! with proptest-generated bytes) and the `structured` fuzz target
//! (`fuzz/src/lib.rs` includes it with `#[path]`).

#![allow(dead_code)]

use arbitrary::Unstructured;

/// A generated program.
#[derive(Clone, Debug)]
pub struct Generated {
    /// The K source text.
    pub source: String,
    /// `true` if the text was generated in valid mode and must parse without
    /// diagnostics.
    pub valid: bool,
}

/// Generates one program from `u`.
pub fn generate(u: &mut Unstructured<'_>) -> Generated {
    // Noisy one time in three; exhausted input (index 0) is valid.
    let noisy = u.choose_index(3).unwrap_or(0) == 2;
    let mut g = Gen {
        u,
        out: String::new(),
        indent: 0,
        newline: "\n",
        noisy,
        budget: 600,
        depth: 0,
        inline: false,
    };
    g.newline = match g.pick(8) {
        0 => "\r\n",
        _ => "\n",
    };
    g.file();
    Generated {
        source: g.out,
        valid: !noisy,
    }
}

