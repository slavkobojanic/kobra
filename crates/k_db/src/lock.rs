//! `schema.lock`: the schema the migrations produce, committed with the
//! app (`docs/design/19-persistence.md`, "The `schema.lock` file").
//!
//! The canonical layout is produced by [`SchemaLock::to_toml`]: a header
//! comment, the `migrations` list, then one `[tables.<name>]` section per
//! table in name order, each with `entity` and a multi-line `columns`
//! array of inline tables in column order. Keys inside a column are
//! written in a fixed order and omitted when false or empty, so diffs stay
//! small. [`SchemaLock::parse`] accepts any valid TOML with that structure.

use std::collections::BTreeMap;
use std::fmt::Write;

use serde::Deserialize;

/// The first line of every generated `schema.lock`.
pub const HEADER: &str = "# Generated by `k migrate`. Do not edit by hand.";

/// One column as recorded in the lock.
#[derive(Clone, PartialEq, Eq, Debug, Default, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct LockedColumn {
    /// The entity field; absent for a retired column.
    #[serde(default)]
    pub field: Option<String>,
    /// The locked column name.
    pub name: String,
    /// The `schema.lock` type name ([`crate::schema::ColumnType::lock_name`]).
    #[serde(rename = "type")]
    pub ty: String,
    /// `primaryKey = true`.
    #[serde(default)]
    pub primary_key: bool,
    /// `nullable = true`.
    #[serde(default)]
    pub nullable: bool,
    /// `unique = true`.
    #[serde(default)]
    pub unique: bool,
    /// `indexed = true`.
    #[serde(default)]
    pub indexed: bool,
    /// `references = "table.id"`.
    #[serde(default)]
    pub references: Option<String>,
    /// The case names of an `enumeration` column.
    #[serde(default)]
    pub cases: Vec<String>,
    /// The default, as text (`"awaitingPayment"`, `"false"`). A TOML
    /// boolean or number (`default = false`) reads as its text.
    #[serde(default, deserialize_with = "scalar_text")]
    pub default: Option<String>,
    /// `retired = true`: the field was removed; the column is dropped by a
    /// later migration.
    #[serde(default)]
    pub retired: bool,
}

/// Reads a TOML string, boolean, integer or float as text.
///
/// # Errors
///
/// The value is an array, a table or a datetime.
fn scalar_text<'de, D: serde::Deserializer<'de>>(d: D) -> Result<Option<String>, D::Error> {
    use serde::de::Error;
    match toml::Value::deserialize(d)? {
        toml::Value::String(s) => Ok(Some(s)),
        toml::Value::Boolean(b) => Ok(Some(b.to_string())),
        toml::Value::Integer(i) => Ok(Some(i.to_string())),
        toml::Value::Float(f) => Ok(Some(f.to_string())),
        _ => Err(D::Error::custom("a default is a string, boolean or number")),
    }
}

/// One table as recorded in the lock.
#[derive(Clone, PartialEq, Eq, Debug, Default, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LockedTable {
    /// The qualified entity name.
    pub entity: String,
    /// `retired = true`: the entity was removed; the table is dropped by a
    /// later migration.
    #[serde(default)]
    pub retired: bool,
    /// The columns, in order.
    #[serde(default)]
    pub columns: Vec<LockedColumn>,
}

/// The newest `schema.lock` format this toolchain reads and writes
/// (`docs/design/48-releases-and-versioning.md`, "Lockfile format
/// versions"; `k_sema::lockformat` has every lockfile's).
pub const FORMAT: u32 = 1;

/// The whole lock.
#[derive(Clone, PartialEq, Eq, Debug, Default, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SchemaLock {
    /// `format = N` when the lock says it; `None` is format 1, as every
    /// lock written before the key existed. [`SchemaLock::to_toml`] writes
    /// it back, so a lock keeps the format it was read in.
    #[serde(default)]
    pub format: Option<u32>,
    /// The applied migrations, in order (`0001_init`, …).
    #[serde(default)]
    pub migrations: Vec<String>,
    /// The tables, by locked name.
    #[serde(default)]
    pub tables: BTreeMap<String, LockedTable>,
}

/// Why a `schema.lock` couldn't be read.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct LockError {
    /// What is wrong, with the TOML parser's location when it has one.
    pub message: String,
    /// What is wrong, without the location: for a diagnostic that points
    /// at [`LockError::span`].
    pub reason: String,
    /// The byte range of the offending text, when the parser knows it.
    pub span: Option<std::ops::Range<usize>>,
}

impl std::fmt::Display for LockError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "schema.lock: {}", self.message)
    }
}

impl std::error::Error for LockError {}

/// Writes `s` as a TOML basic string, escaping quotes, backslashes and
/// control characters.
fn quote(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() => {
                let _ = write!(out, "\\u{:04X}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Writes `s` as a TOML key: bare when it only has ASCII letters, digits,
/// `_` and `-`, else quoted with [`quote`].
fn key(s: &str) -> String {
    if !s.is_empty()
        && s.chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
    {
        s.to_owned()
    } else {
        quote(s)
    }
}

impl SchemaLock {
    /// Parses a lock.
    ///
    /// # Errors
    ///
    /// Invalid TOML, unknown keys, wrongly typed values, or a `format`
    /// this toolchain doesn't read (0, or newer than [`FORMAT`]).
    pub fn parse(text: &str) -> Result<SchemaLock, LockError> {
        let lock: SchemaLock = toml::from_str(text).map_err(|e: toml::de::Error| LockError {
            message: e.to_string(),
            reason: e.message().to_owned(),
            span: e.span(),
        })?;
        match lock.format {
            Some(n) if n == 0 || n > FORMAT => {
                let reason = format!(
                    "schema.lock is in format {n}, and this toolchain reads formats 1 to {FORMAT}"
                );
                Err(LockError {
                    message: reason.clone(),
                    reason,
                    span: text.find("format").map(|at| at..at + "format".len()),
                })
            }
            _ => Ok(lock),
        }
    }

    /// Writes the lock in its canonical layout. `parse(to_toml(l)) == l`
    /// for every lock.
    #[must_use]
    pub fn to_toml(&self) -> String {
        let mut out = String::new();
        out.push_str(HEADER);
        out.push('\n');
        if let Some(n) = self.format {
            let _ = writeln!(out, "format = {n}");
        }
        let names: Vec<String> = self.migrations.iter().map(|m| quote(m)).collect();
        let _ = writeln!(out, "migrations = [{}]", names.join(", "));
        for (name, table) in &self.tables {
            let _ = write!(
                out,
                "\n[tables.{}]\nentity = {}\n{}columns = [\n",
                key(name),
                quote(&table.entity),
                if table.retired {
                    "retired = true\n"
                } else {
                    ""
                }
            );
            for c in &table.columns {
                let mut parts = Vec::new();
                if let Some(f) = &c.field {
                    parts.push(format!("field = {}", quote(f)));
                }
                parts.push(format!("name = {}", quote(&c.name)));
                parts.push(format!("type = {}", quote(&c.ty)));
                for (flag, on) in [
                    ("primaryKey", c.primary_key),
                    ("nullable", c.nullable),
                    ("unique", c.unique),
                    ("indexed", c.indexed),
                ] {
                    if on {
                        parts.push(format!("{flag} = true"));
                    }
                }
                if let Some(r) = &c.references {
                    parts.push(format!("references = {}", quote(r)));
                }
                if !c.cases.is_empty() {
                    let cases: Vec<String> = c.cases.iter().map(|k| quote(k)).collect();
                    parts.push(format!("cases = [{}]", cases.join(", ")));
                }
                if let Some(d) = &c.default {
                    parts.push(format!("default = {}", quote(d)));
                }
                if c.retired {
                    parts.push("retired = true".to_owned());
                }
                let _ = writeln!(out, "    {{ {} }},", parts.join(", "));
            }
            out.push_str("]\n");
        }
        out
    }
}
