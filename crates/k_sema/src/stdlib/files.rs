//! The list of embedded standard-library files.
//!
//! Every `.k` file below `crates/k_sema/stdlib/` must be listed here, in
//! byte order of its path; `tests::embedded_files_match_the_directory`
//! fails otherwise. To add a file, create it and add its path to the list.

/// Embeds the listed files: each entry is the path below `stdlib/` and the
/// file's text.
macro_rules! stdlib_files {
    ($($path:literal),* $(,)?) => {
        /// Every file of the embedded standard library, sorted by path: the
        /// path below `crates/k_sema/stdlib/` and the file's text.
        pub(crate) const FILES: &[(&str, &str)] = &[
            $( ($path, include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/stdlib/", $path))) ),*
        ];
    };
}

