//! `k upgrade` end to end (`docs/design/48-releases-and-versioning.md`,
//! "Upgrading a project"; `docs/compiler/release.md` §12 step 8).
//!
//! Each fixture is an app pinned to the minor before the running
//! toolchain's (`k = "0.0"` and `toolchain = "0.0.3"` while this is
//! `0.1.x`), committed to a fresh git repository. Newer toolchains are
//! fakes in `$K_HOME/toolchains/<version>/k`: shell scripts that append
//! their version, arguments and `K_TOOLCHAIN_DELEGATED` to a log and exit
//! 0. That the lockfile conversion turns every golden lock into the
//! current format is `k_server`'s `compat::locks::` test; which guide
//! section a remaining problem gets is a unit test of `upgrade.rs`.

#![allow(clippy::unwrap_used, clippy::panic)]

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

use k_sema::workspace::Version;

/// The running toolchain's version.
fn running() -> Version {
    Version::parse(env!("CARGO_PKG_VERSION")).unwrap()
}

/// The minor `offset` minors from the running one (`0.0` for -1 while
/// this is 0.1.x).
fn minor(offset: i64) -> String {
    let v = running();
    let m = i64::try_from(v.minor).unwrap() + offset;
    assert!(
        m >= 0,
        "the running toolchain has no minor {offset} from it"
    );
    format!("{}.{m}", v.major)
}

/// A project in a git repository, and a `K_HOME`; removed when dropped.
struct Fixture {
    root: PathBuf,
}

impl Fixture {
    fn new(tag: &str) -> Fixture {
        let n = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_or(0, |d| d.as_nanos());
        let root = std::env::temp_dir().join(format!("k_upgrade_{tag}_{}_{n}", std::process::id()));
        fs::create_dir_all(root.join("home/toolchains")).unwrap();
        fs::create_dir_all(root.join("project")).unwrap();
        Fixture { root }
    }

    fn home(&self) -> PathBuf {
        self.root.join("home")
    }

    fn project(&self) -> PathBuf {
        self.root.join("project")
    }

    fn log(&self) -> PathBuf {
        self.root.join("calls.log")
    }

    fn write(&self, relative: &str, text: &str) {
        let path = self.project().join(relative);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, text).unwrap();
    }

    fn read(&self, relative: &str) -> String {
        fs::read_to_string(self.project().join(relative)).unwrap()
    }

    /// An app requiring the previous minor, locked to its patch 3, using a
    /// deprecated function of its own; committed.
    fn app(&self, body: &str) {
        self.write(
            "k.toml",
            &format!("[package]\nname = \"demo\"\nk = \"{}\"\n", minor(-1)),
        );
        self.write(
            "k.lock",
            &format!(
                "# k.lock: generated by `k build`; commit it.\n\ntoolchain = \"{}.3\"\n",
                minor(-1)
            ),
        );
        self.write("App.k", "public app Demo {}\n");
        self.write("src/demo/Sum.k", body);
        self.git(&["init", "-q"]);
        self.commit();
    }

    fn commit(&self) {
        self.git(&["add", "-A"]);
        self.git(&[
            "-c",
            "user.name=k",
            "-c",
            "user.email=k@example.com",
            "commit",
            "-q",
            "-m",
            "fixture",
        ]);
    }

    fn git(&self, args: &[&str]) {
        let status = Command::new("git")
            .args(args)
            .current_dir(self.project())
            .env("GIT_CONFIG_NOSYSTEM", "1")
            .env("HOME", &self.root)
            .status()
            .unwrap();
        assert!(status.success(), "git {args:?}");
    }

    /// Installs a fake toolchain `version` that logs its call and exits 0.
    #[cfg(unix)]
    fn install(&self, version: &str) {
        use std::os::unix::fs::PermissionsExt;
        let dir = self.home().join("toolchains").join(version);
        fs::create_dir_all(&dir).unwrap();
        let exe = dir.join(Path::new(env!("CARGO_BIN_EXE_k")).file_name().unwrap());
        fs::write(
            &exe,
            format!(
                "#!/bin/sh\necho \"{version} delegated=$K_TOOLCHAIN_DELEGATED $*\" >> '{}'\nexit 0\n",
                self.log().display()
            ),
        )
        .unwrap();
        fs::set_permissions(&exe, fs::Permissions::from_mode(0o755)).unwrap();
    }

    /// The fakes' calls, one line each.
    fn calls(&self) -> Vec<String> {
        fs::read_to_string(self.log())
            .unwrap_or_default()
            .lines()
            .map(str::to_owned)
            .collect()
    }

    fn k(&self, args: &[&str]) -> Output {
        Command::new(env!("CARGO_BIN_EXE_k"))
            .args(args)
            .current_dir(self.project())
            .env("K_HOME", self.home())
            .env("HOME", &self.root)
            .env("GIT_CONFIG_NOSYSTEM", "1")
            .env_remove("K_TOOLCHAIN")
            .env_remove("K_TOOLCHAIN_DELEGATED")
            .output()
            .expect("run k")
    }
}

impl Drop for Fixture {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.root);
    }
}

fn stderr(out: &Output) -> String {
    String::from_utf8_lossy(&out.stderr).into_owned()
}

/// A deprecated function whose replacement has the same labels, and a use
/// of it: K1401 with a machine-applicable fix.
const DEPRECATED: &str = "@Deprecated(\"use `total(of:)`\", since: \"0.1\", replacement: \"total(of:)\")\n\
func sum(of values: List<Int>) -> Int {\n    return total(of: values)\n}\n\n\
func total(of values: List<Int>) -> Int {\n    return 0\n}\n\n\
func report() -> Int {\n    return sum(of: [1, 2])\n}\n";

#[test]
fn moves_the_project_to_this_toolchain() {
    let f = Fixture::new("here");
    f.app(DEPRECATED);
    let out = f.k(&["upgrade"]);
    let err = stderr(&out);
    assert_eq!(out.status.code(), Some(0), "{err}");
    // The deprecation's fix, the requirement and the lock.
    assert!(
        f.read("src/demo/Sum.k")
            .contains("return total(of: [1, 2])")
    );
    assert!(
        f.read("k.toml").contains(&format!("k = \"{}\"", minor(0))),
        "{}",
        f.read("k.toml")
    );
    assert_eq!(
        f.read("k.lock"),
        format!(
            "# k.lock: generated by `k build`; commit it.\n\ntoolchain = \"{}\"\n",
            running()
        )
    );
    assert!(
        err.contains(&format!("from k {}.3 to k {}", minor(-1), running())),
        "{err}"
    );
    assert!(err.contains("no problems remain"), "{err}");
    // One minor: no warning about rolling deploys.
    assert!(!err.contains("rolling deploy"), "{err}");
}

#[test]
fn applies_only_migration_fixes_and_prints_what_remains() {
    let f = Fixture::new("remains");
    // `== true` has a machine-applicable fix (K2012) that isn't a
    // migration, and `missing` is an error nothing fixes.
    let body = format!(
        "{DEPRECATED}\nfunc isOpen(done: Bool) -> Bool {{\n    return done == true\n}}\n\nfunc broken() -> Int {{\n    return missing\n}}\n"
    );
    f.app(&body);
    let out = f.k(&["upgrade", "--color", "never"]);
    let err = stderr(&out);
    assert_eq!(out.status.code(), Some(1), "{err}");
    let text = f.read("src/demo/Sum.k");
    assert!(text.contains("return total(of: [1, 2])"), "{text}");
    assert!(text.contains("done == true"), "not a migration: {text}");
    assert!(err.contains("K2012"), "{err}");
    assert!(err.contains("missing"), "{err}");
    assert!(err.contains("apps/upgrading.md"), "{err}");
    // The project still moved.
    assert!(f.read("k.toml").contains(&format!("k = \"{}\"", minor(0))));
}

#[test]
fn refuses_uncommitted_changes() {
    let f = Fixture::new("dirty");
    f.app(DEPRECATED);
    f.write(
        "src/demo/Extra.k",
        "func extra() -> Int {\n    return 1\n}\n",
    );
    let out = f.k(&["upgrade"]);
    let err = stderr(&out);
    assert_eq!(out.status.code(), Some(2), "{err}");
    assert!(err.contains("uncommitted changes"), "{err}");
    assert!(err.contains("src/demo/Extra.k"), "{err}");
    assert!(err.contains("--allow-dirty"), "{err}");
    assert!(
        f.read("k.toml").contains(&format!("k = \"{}\"", minor(-1))),
        "nothing changed"
    );
    assert!(f.read("src/demo/Sum.k").contains("return sum(of: [1, 2])"));

    let out = f.k(&["upgrade", "--allow-dirty"]);
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));
    assert!(f.read("k.toml").contains(&format!("k = \"{}\"", minor(0))));
}

#[test]
fn refuses_a_project_outside_git_without_allow_dirty() {
    let f = Fixture::new("nogit");
    f.app(DEPRECATED);
    fs::remove_dir_all(f.project().join(".git")).unwrap();
    let out = f.k(&["upgrade"]);
    let err = stderr(&out);
    assert_eq!(out.status.code(), Some(2), "{err}");
    assert!(err.contains("git"), "{err}");
    assert!(err.contains("--allow-dirty"), "{err}");
}

#[test]
fn refuses_to_move_a_project_back() {
    let f = Fixture::new("back");
    f.app(DEPRECATED);
    f.write(
        "k.toml",
        &format!("[package]\nname = \"demo\"\nk = \"{}\"\n", minor(1)),
    );
    f.write("k.lock", &format!("toolchain = \"{}.0\"\n", minor(1)));
    f.commit();
    let out = f.k(&["upgrade"]);
    let err = stderr(&out);
    assert_eq!(out.status.code(), Some(2), "{err}");
    assert!(err.contains("newer than"), "{err}");
}

#[test]
fn a_lockfile_too_new_stops_it_before_anything_changes() {
    let f = Fixture::new("toonew");
    f.app(DEPRECATED);
    f.write("rpc.lock", "# rpc.lock\n\nformat = 99\n");
    f.commit();
    let out = f.k(&["upgrade"]);
    let err = stderr(&out);
    assert_eq!(out.status.code(), Some(2), "{err}");
    assert!(err.contains("K8202"), "{err}");
    assert!(f.read("src/demo/Sum.k").contains("return sum(of: [1, 2])"));
    assert!(f.read("k.toml").contains(&format!("k = \"{}\"", minor(-1))));
}

#[cfg(unix)]
#[test]
fn steps_through_each_minor_in_between() {
    let f = Fixture::new("steps");
    f.app(DEPRECATED);
    let (next, last) = (minor(1), minor(2));
    f.install(&format!("{next}.0"));
    f.install(&format!("{next}.4"));
    f.install(&format!("{next}.5-rc.1"));
    f.install(&format!("{last}.1"));
    let out = f.k(&["upgrade", "--to", &last]);
    let err = stderr(&out);
    assert_eq!(out.status.code(), Some(0), "{err}");
    // This toolchain's minor first, here; then each later minor's newest
    // release, in order, each moving the project to itself.
    assert!(
        f.read("src/demo/Sum.k")
            .contains("return total(of: [1, 2])")
    );
    assert!(f.read("k.toml").contains(&format!("k = \"{}\"", minor(0))));
    assert_eq!(
        f.calls(),
        [
            format!("{next}.4 delegated=1 upgrade --to {next}.4 --allow-dirty ."),
            format!("{last}.1 delegated=1 upgrade --to {last}.1 --allow-dirty ."),
        ]
    );
    assert!(err.contains("rolling deploy"), "{err}");
}

#[cfg(unix)]
#[test]
fn a_missing_minor_in_between_stops_it_before_anything_changes() {
    let f = Fixture::new("gap");
    f.app(DEPRECATED);
    let last = minor(2);
    f.install(&format!("{last}.0"));
    let out = f.k(&["upgrade", "--to", &format!("{last}.0")]);
    let err = stderr(&out);
    assert_eq!(out.status.code(), Some(2), "{err}");
    assert!(
        err.contains(&format!("k toolchain install {}", minor(1))),
        "{err}"
    );
    assert!(f.calls().is_empty());
    assert!(f.read("k.toml").contains(&format!("k = \"{}\"", minor(-1))));
}

